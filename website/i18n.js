function applyLanguage(lang) {
  const base = translations[lang] || translations.en;
  const pageExtra = (window.SOLUTIONS_PAGE_I18N && (window.SOLUTIONS_PAGE_I18N[lang] || window.SOLUTIONS_PAGE_I18N.en)) || {};
  const t = Object.assign({}, base, pageExtra);
  document.querySelectorAll('[data-i18n]').forEach(el => {
    const key = el.getAttribute('data-i18n');
    if (t[key]) el.textContent = t[key];
  });
  if (pageExtra.pageTitle) {
    document.title = pageExtra.pageTitle;
  }
  document.documentElement.lang = lang;
  localStorage.setItem('synthux-lang', lang);

  // Sync custom lang pickers
  document.querySelectorAll('.lang-picker').forEach(picker => {
    const label = picker.querySelector('.lang-picker__label');
    if (label) label.textContent = langLabels[lang] || lang.toUpperCase();

    // Mark active item
    picker.querySelectorAll('.lang-picker__menu button').forEach(btn => {
      const btnLang = btn.getAttribute('onclick')?.match(/'(\w+)'/)?.[1];
      btn.classList.toggle('active', btnLang === lang);
    });
  });
}

function getLanguage() {
  const saved = localStorage.getItem('synthux-lang');
  if (saved && translations[saved]) return saved;

  // Auto-detect browser language
  const browserLang = (navigator.language || '').toLowerCase();
  for (const lang of langOrder) {
    if (browserLang.startsWith(lang)) return lang;
  }
  if (browserLang.startsWith('zh')) return 'zh';
  return 'en';
}

function toggleLangPicker(id) {
  const picker = document.getElementById(id);
  if (!picker) return;

  // Close all other pickers first
  document.querySelectorAll('.lang-picker.open').forEach(p => {
    if (p.id !== id) p.classList.remove('open');
  });

  // Close desktop Solutions dropdown if open
  document.querySelectorAll('.nav-item.dropdown-open').forEach(el => {
    el.classList.remove('dropdown-open');
    const trigger = el.querySelector('.nav-link');
    if (trigger) trigger.setAttribute('aria-expanded', 'false');
  });

  picker.classList.toggle('open');
}

function pickLang(lang) {
  applyLanguage(lang);
  // Close all pickers
  document.querySelectorAll('.lang-picker.open').forEach(p => p.classList.remove('open'));
}

// Close picker on outside click
document.addEventListener('click', (e) => {
  if (!e.target.closest('.lang-picker')) {
    document.querySelectorAll('.lang-picker.open').forEach(p => p.classList.remove('open'));
  }
});

function toggleLanguage() {
  const current = getLanguage();
  const idx = langOrder.indexOf(current);
  const next = langOrder[(idx + 1) % langOrder.length];
  applyLanguage(next);
}


